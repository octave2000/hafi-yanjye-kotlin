#!/usr/bin/env node
/**
 * Turns Lucide icons (the same set the web app uses) into Android vector
 * drawables, so both apps show identical icons without an icon library.
 *
 *   node tools/icons.mjs <path to lucide-react/dist/esm/icons>
 *
 * Writes app/src/main/res/drawable/ic_<name>.xml for every name in tools/icons.txt.
 * Vector drawables only know <path>, so circles, rects and lines become paths.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

// One Lucide name per line (kebab-case, as in lucide-react/dist/esm/icons).
// Add a line and run this script again to get a new icon.
const ICONS = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "icons.txt"), "utf8")
	.split("\n")
	.map((line) => line.trim())
	.filter((line) => line && !line.startsWith("#"));

const n = (v, fallback = 0) => (v === undefined ? fallback : Number(v));

function circle(cx, cy, rx, ry = rx) {
	return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0Z`;
}

function rect(a) {
	const x = n(a.x);
	const y = n(a.y);
	const w = n(a.width);
	const h = n(a.height);
	let rx = n(a.rx, n(a.ry));
	let ry = n(a.ry, rx);
	rx = Math.min(rx, w / 2);
	ry = Math.min(ry, h / 2);
	if (!rx || !ry) return `M${x} ${y}h${w}v${h}h${-w}Z`;
	return [
		`M${x + rx} ${y}`,
		`h${w - 2 * rx}`,
		`a${rx} ${ry} 0 0 1 ${rx} ${ry}`,
		`v${h - 2 * ry}`,
		`a${rx} ${ry} 0 0 1 ${-rx} ${ry}`,
		`h${-(w - 2 * rx)}`,
		`a${rx} ${ry} 0 0 1 ${-rx} ${-ry}`,
		`v${-(h - 2 * ry)}`,
		`a${rx} ${ry} 0 0 1 ${rx} ${-ry}`,
		"Z",
	].join("");
}

function points(value, close) {
	const nums = String(value).trim().split(/[\s,]+/).map(Number);
	let d = "";
	for (let i = 0; i + 1 < nums.length; i += 2)
		d += `${i === 0 ? "M" : "L"}${nums[i]} ${nums[i + 1]}`;
	return close ? `${d}Z` : d;
}

function toPath(tag, a) {
	switch (tag) {
		case "path":
			return a.d;
		case "circle":
			return circle(n(a.cx), n(a.cy), n(a.r));
		case "ellipse":
			return circle(n(a.cx), n(a.cy), n(a.rx), n(a.ry));
		case "rect":
			return rect(a);
		case "line":
			return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
		case "polyline":
			return points(a.points, false);
		case "polygon":
			return points(a.points, true);
		default:
			throw new Error(`Unsupported element <${tag}>`);
	}
}

function drawable(node) {
	const paths = node.map(([tag, a]) => {
		const filled = a.fill === "currentColor";
		return [
			"    <path",
			`        android:pathData="${toPath(tag, a)}"`,
			`        android:fillColor="${filled ? "#FF000000" : "#00000000"}"`,
			'        android:strokeColor="#FF000000"',
			'        android:strokeWidth="2"',
			'        android:strokeLineCap="round"',
			'        android:strokeLineJoin="round" />',
		].join("\n");
	});
	return [
		'<?xml version="1.0" encoding="utf-8"?>',
		"<!-- Generated by tools/icons.mjs from Lucide (ISC license). Do not edit. -->",
		'<vector xmlns:android="http://schemas.android.com/apk/res/android"',
		'    android:width="24dp"',
		'    android:height="24dp"',
		'    android:viewportWidth="24"',
		'    android:viewportHeight="24">',
		...paths,
		"</vector>",
		"",
	].join("\n");
}

const source = process.argv[2];
if (!source) {
	console.error("Usage: node tools/icons.mjs <lucide-react/dist/esm/icons>");
	process.exit(1);
}
const out = join(
	dirname(fileURLToPath(import.meta.url)),
	"../app/src/main/res/drawable",
);
mkdirSync(out, { recursive: true });

for (const name of ICONS) {
	// A renamed icon is a one-line re-export of the new file: follow it.
	let path = resolve(source, `${name}.mjs`);
	const alias = readFileSync(path, "utf8").match(
		/export \{ default \} from '\.\/([a-z0-9-]+\.mjs)'/,
	);
	if (alias) path = resolve(source, alias[1]);
	const node = (await import(pathToFileURL(path).href)).__iconData?.node;
	if (!node) throw new Error(`No icon data for "${name}"`);
	writeFileSync(
		join(out, `ic_${name.replaceAll("-", "_")}.xml`),
		drawable(node),
	);
}
console.log(`Wrote ${ICONS.length} icons to ${out}`);
